ALL_SUB_SYSTEM = ("你是图书检索员。用户会问一个问题，你要从图书的小节清单里"
                  "挑出最可能回答它的小节。只输出小节号，不要解释。")

ALL_SUB_CACHE = "allsub_cache_%s.json" % hashlib.md5(
    ALL_SUB_TEMPLATE.encode("utf-8")).hexdigest()[:8]


def route_allsubs(question, key=None, n=3, use_cache=True):
    """直接在全量小节列表里选，返回 (小节号列表, 原始输出)

    失败退化成 ([], "")：调用方该退回章节路由，而不是干等。
    """
    if use_cache and os.path.exists(ALL_SUB_CACHE):
        cache = json.load(open(ALL_SUB_CACHE, encoding="utf-8"))
        if question in cache:
            v = cache[question]
            return (v["got"] if isinstance(v, dict) else v), v.get("raw", "") if isinstance(v, dict) else ""

    valid = {a for lst in SUBS.values() for a, _ in lst}
    if not valid:
        return [], ""
    try:
        txt, _ = ask_llm(ALL_SUB_TEMPLATE % (_all_body(), question),
                         key or load_key(), ALL_SUB_SYSTEM,
                         temperature=0.0, max_tokens=80)
    except Exception as e:
        print("   ! 小节直选失败：%s" % e)
        return [], ""

    got = parse_sub(txt, valid)[:n]
    if use_cache:
        cache = {}
        if os.path.exists(ALL_SUB_CACHE):
            cache = json.load(open(ALL_SUB_CACHE, encoding="utf-8"))
        cache[question] = {"got": got, "raw": txt.strip()}
        json.dump(cache, open(ALL_SUB_CACHE, "w", encoding="utf-8"),
                  ensure_ascii=False, indent=1)
    return got, txt.strip()


def secs_of_subs(subs):
    """小节号列表 → 去重后的章节标题（保持小节给出的顺序）

    顺序很重要：search_multi 按位置给章节分档加分（0.6 / 0.2 / 0）。
    小节排序本身就是模型给的把握，直接沿用，不要重新按章号排。
    """
    out = []
    for no in subs:
        sec = ".".join(no.split(".")[:2])
        t = SEC_TITLE.get(sec)
        if t and t not in out:
            out.append(t)
    return out
