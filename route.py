def parse_sub(txt, valid):
    """只认清单里真实存在的小节号

    和章节号不同，三级号（10.2.5）没有「编号串味」的土壤，但仍有
    「写出一个不存在的小节」的情况（比如 12.4.9，这章只有 8 个小节）。
    不在清单里的一律丢弃——宁可少一个候选，也不要拿一个幻觉号去加分。
    """
    out = []
    for m in re.finditer(r"(\d+\.\d+\.\d+)\s*[:：]?\s*(\d{1,3})?", txt):
        no = m.group(1)
        if no in valid and no not in out:
            out.append(no)
    return out


def route_sub(question, picks, key=None, n=3, use_cache=True):
    """在已选中的几个章节里挑小节。返回 (小节号列表, 原始输出)

    失败退化成 ([], "")，调用方按「没有小节信号」继续跑——这一层是加分项，
    不是必经环节，缺了它结果应该和没做这件事的时候一样。
    """
    if not picks:
        return [], ""

    if use_cache:
        cache = _sub_load()
        if question in cache:
            return cache[question], cache.get(question + "|raw", "")

    blocks, valid = [], set()
    for p in picks:
        lst = SUBS.get(p.strip()) or SUBS.get(p.strip() + " ")
        if not lst:
            continue
        blocks.append("【%s】\n%s" % (p.replace("## ", "").strip(),
                                     "\n".join("%s %s" % (a, b) for a, b in lst)))
        valid |= {a for a, _ in lst}
    if not blocks:
        return [], ""

    try:
        txt, _ = ask_llm(SUB_TEMPLATE % ("\n\n".join(blocks), question),
                         key or load_key(), SUB_SYSTEM, temperature=0.0, max_tokens=80)
    except Exception as e:
        print("   ! 小节路由失败，只用章节：%s" % e)
        return [], ""

    got = parse_sub(txt, valid)[:n]
    if use_cache:
        cache = _sub_load()
        cache[question] = got
        cache[question + "|raw"] = txt.strip()
        _sub_save(cache)
    return got, txt.strip()


def sub_conf(txt, n=3):
    """原始输出里的匹配度，按出现顺序。抽不到给 100（和章节那边一致）"""
    out = []
    for m in re.finditer(r"\d+\.\d+\.\d+\s*[:：]?\s*(\d{1,3})", txt or ""):
        v = int(m.group(1))
        out.append(v if 0 < v <= 100 else 100)
        if len(out) >= n:
            break
    return out


