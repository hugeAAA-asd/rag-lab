def _conf_after(txt, pos):
    """章节号后面紧跟的匹配度，没有就返回 100

    只认「章节号 + 冒号/括号 + 数字」这一种写法（`8.3:92`、`8.3（92）`）。
    不认 `8.3, 92分` —— 因为裸逗号后面紧跟的数字，在模型混答
    `50,48,3.1` 时本身就是章节号，放开就分不清「分数」和「章节」了。
    """
    seg = txt[pos:pos + 10]
    m = re.match(r"\s*[:：]\s*(\d{1,3})", seg) or re.match(r"\s*[（(]\s*(\d{1,3})", seg)
    if not m:
        return 100
    v = int(m.group(1))
    return v if 0 < v <= 100 else 100


# 「No.52:88」「8.3:92」「4.2（91）」——三种写法一条正则
_ITEM = re.compile(r"(No\.?\s*)?(\d+(?:\.\d+)?)\s*(?:[:：]|[（(])\s*(\d{1,3})(?!\d)", re.I)


def _parse_detail(txt, n):
    """返回 [(章节标题, 匹配度)]——匹配度抽不到就是 100

    解析顺序：先按「带分数」的三种写法全收，收不到再退回旧的无分数逻辑。

    为什么改成这个顺序：prompt 要求每条都带分数之后，模型开始混着写
    `50:80,48:45,3.1:20`（编号和小节号一起出现）。旧的「三级互斥」写法
    在这种情况下只取到 3.1，把真正排第一的 No.50 丢了——而且不报错，
    表现是「模型越大越聪明吗」这题时对时错，像模型不稳定，其实是解析器。
    """
    if "NONE" in txt.upper():
        return []

    out = []

    def add(title, conf):
        if any(t == title for t, _ in out):
            return
        out.append((title, conf))

    def ok(v):
        return v if 0 < v <= 100 else 100

    # 一条正则横扫三种写法，**按原文顺序**收集：
    #   「No.52:88」编号+冒号　「8.3:92」章节号+冒号　「4.2（91）」括号
    # 为什么不分三段扫：分段是按「格式」排序，不是按原文排序。
    # 模型混答 `50:80,48:45,3.1:20` 时三段先后会被打乱；同一个章节
    # 在不同段里重复出现时，留下谁的分取决于扫描顺序，而不是模型的意思。
    for m in _ITEM.finditer(txt):
        pre, num, conf = m.group(1), m.group(2), ok(int(m.group(3)))
        if pre:                        # No.52 → 编号
            i = int(num) - 1
            if 0 <= i < len(TITLES):
                add(TITLES[i], conf)
        elif "." in num:               # 8.3 → 章节号
            for t in TITLES:
                if t.startswith("## " + num):
                    add(t, conf)
                    break
        else:                          # 裸整数 → 编号
            i = int(num) - 1
            if 0 <= i < len(TITLES):
                add(TITLES[i], conf)

    if out:
        return out[:n]

    # ── 下面是无分数的旧逻辑，只为兼容 prompt 改动之前存的缓存 ──
    for m in re.finditer(r"\d+\.\d+", txt):
        for t in TITLES:
            if t.startswith("## " + m.group()):
                add(t, 100)
                break

    if not out:
        for m in re.finditer(r"[Nn]o\.?\s*(\d+)", txt):
            i = int(m.group(1)) - 1
            if 0 <= i < len(TITLES):
                add(TITLES[i], 100)

    if not out and not re.search(r"\d+\.\d+", txt):
        for m in re.finditer(r"(?<![:：])\d+", txt):
            i = int(m.group()) - 1
            if 0 <= i < len(TITLES):
                add(TITLES[i], 100)

    return out[:n]


def _parse(txt, n):
    """只要章节标题（旧接口，保留兼容）"""
    return [t for t, _ in _parse_detail(txt, n)]


def parse_conf(txt, n=3):
    """章节对应的匹配度列表，和 _parse 的结果一一对应

    旧缓存（prompt 改成带分数之前存的原始输出里只有章节号）抽不到分数，
    全部返回 100 —— 等于「按全额加分」，自动退回改动前的行为。
    这样同一个 route_cache.json 里新旧两种记录能共存：
    想对比新旧方案，换的是缓存，不是代码。
    """
    return [c for _, c in _parse_detail(txt, n)]


def route(question, key=None, n=3, use_cache=True):
    """返回（章节标题列表, 原始输出）。失败返回 ([], "")——降级路径。

    use_cache 默认开：路由虽然用 temperature=0，但同一个问题偶尔也会给出
    不同章节；更重要的是每次都要把 1580 字的目录重发一遍。
    缓存到 route_cache.json 之后，评估可复现，线上也省一次调用。
    """
    if use_cache:
        cache = _load()
        if question in cache:
            return cache[question], cache[question + "|raw"]

    try:
        txt, _ = ask_llm(ROUTE_TEMPLATE % (MENU, question), key or load_key(),
                         ROUTE_SYSTEM, temperature=0.0)
    except Exception as e:
        print("   ! 路由失败，退回纯检索：%s" % e)
        return [], ""

    picks = _parse(txt, n)
    if use_cache:
        cache = _load()
        cache[question] = picks
        cache[question + "|raw"] = txt.strip()
        _save(cache)
    return picks, txt.strip()


